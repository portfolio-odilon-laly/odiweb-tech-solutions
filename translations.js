let currentLanguage = "fr";


/* Traduire une clé */

function translate(key) {

    return translations[currentLanguage]?.[key] || key;

}


/* Appliquer les traductions à la page */

function applyTranslations(language) {

    if (!translations[language]) {
        language = "fr";
    }

    currentLanguage = language;

    document.documentElement.lang = language;

    /* Traduction des textes */

    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.getAttribute("data-i18n");

        if (translations[language][key]) {
            element.textContent = translations[language][key];
        }

    });


    /* Traduction des placeholders */

    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {

        const key = element.getAttribute("data-i18n-placeholder");

        if (translations[language][key]) {
            element.placeholder = translations[language][key];
        }

    });


    /* Traduction des textes alternatifs des images */

    document.querySelectorAll("[data-i18n-alt]").forEach(element => {

        const key = element.getAttribute("data-i18n-alt");

        if (translations[language][key]) {
            element.alt = translations[language][key];
        }

    });


    /* Traduction des attributs aria-label */

    document.querySelectorAll("[data-i18n-aria-label]").forEach(element => {

        const key = element.getAttribute("data-i18n-aria-label");

        if (translations[language][key]) {
            element.setAttribute("aria-label", translations[language][key]);
        }

    });


    /* Traduction du contenu meta */

    document.querySelectorAll("[data-i18n-content]").forEach(element => {

        const key = element.getAttribute("data-i18n-content");

        if (translations[language][key]) {
            element.setAttribute("content", translations[language][key]);
        }

    });


    /* Titre de la page */

    document.title = translations[language].page_title || document.title;


    /* Bouton de langue */

    const languageText = document.getElementById("languageText");

    const languageBtn = document.getElementById("languageBtn");

    if (languageText) {
        languageText.textContent = language === "fr" ? "EN" : "FR";
    }

    if (languageBtn) {
        languageBtn.setAttribute(
            "aria-label",
            translations[language].language_aria
        );
    }


    /* Mémoriser la langue choisie */

    localStorage.setItem("odiweb-language", language);


    /* Informer les autres scripts */

    document.dispatchEvent(new CustomEvent("languageChanged", {
        detail: { language: language }
    }));

}


/* Changer de langue */

function setLanguage(language) {

    applyTranslations(language);

}


/* Initialiser le système */

function initializeTranslations() {

    const savedLanguage = localStorage.getItem("odiweb-language");

    const initialLanguage = savedLanguage && translations[savedLanguage]
        ? savedLanguage
        : "fr";

    applyTranslations(initialLanguage);


    /* Bouton de changement de langue */

    const languageBtn = document.getElementById("languageBtn");

    if (languageBtn) {

        languageBtn.addEventListener("click", () => {

            const newLanguage = currentLanguage === "fr" ? "en" : "fr";

            setLanguage(newLanguage);

        });

    }

}


/* Rendre les fonctions accessibles aux autres fichiers */

window.translations = translations;

window.translate = translate;

window.setLanguage = setLanguage;

window.applyTranslations = applyTranslations;

window.getCurrentLanguage = function () {
    return currentLanguage;
};


/* Lancement automatique */

if (document.readyState === "loading") {

    document.addEventListener("DOMContentLoaded", initializeTranslations);

} else {

    initializeTranslations();

}
