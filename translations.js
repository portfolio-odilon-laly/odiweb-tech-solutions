/* ==========================================
   2. LANGUE PAR DÉFAUT
========================================== */

let currentLanguage = localStorage.getItem("odiwebLanguage") || "fr";


/* ==========================================
   3. APPLIQUER UNE TRADUCTION
========================================== */

function applyTranslations(language) {

    if (!translations[language]) {
        language = "fr";
    }

    currentLanguage = language;

    document.documentElement.lang = language;


    /* Traduire les textes */

    document.querySelectorAll("[data-i18n]").forEach(function (element) {

        const key = element.getAttribute("data-i18n");

        if (translations[language][key]) {

            element.textContent = translations[language][key];

        }

    });


    /* Traduire les placeholders */

    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (element) {

        const key = element.getAttribute("data-i18n-placeholder");

        if (translations[language][key]) {

            element.placeholder = translations[language][key];

        }

    });


    /* Traduire les attributs alt des images */

    document.querySelectorAll("[data-i18n-alt]").forEach(function (element) {

        const key = element.getAttribute("data-i18n-alt");

        if (translations[language][key]) {

            element.alt = translations[language][key];

        }

    });


    /* Mettre à jour le bouton de langue */

    const languageButton = document.getElementById("languageBtn");

    if (languageButton) {

        languageButton.textContent = translations[language].language;

        languageButton.setAttribute(
            "aria-label",
            language === "fr" ? "Switch to English" : "Passer en français"
        );

    }


    /* Enregistrer la langue choisie */

    localStorage.setItem("odiwebLanguage", language);

}


/* ==========================================
   4. CHANGER DE LANGUE
========================================== */

function toggleLanguage() {

    const newLanguage = currentLanguage === "fr" ? "en" : "fr";

    applyTranslations(newLanguage);

}


/* ==========================================
   5. BOUTON DE CHANGEMENT DE LANGUE
========================================== */

const languageButton = document.getElementById("languageBtn");

if (languageButton) {

    languageButton.addEventListener("click", toggleLanguage);

}


/* ==========================================
   6. CHARGEMENT DE LA LANGUE ENREGISTRÉE
========================================== */

applyTranslations(currentLanguage);


